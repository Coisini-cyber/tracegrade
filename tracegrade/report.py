"""Render replay results as Markdown or JSON."""

from __future__ import annotations

import json
from collections import Counter
from typing import Dict, List

from .replay import CaseResult, ReplaySummary


def _failure_kind(message: str) -> str:
    """Collapse a failure message to a stable label for the breakdown table."""
    head = message.split(":", 1)[0]
    if head.endswith(")") and "(" in head:
        head = head[: head.rindex("(")].strip()
    return head


def failure_breakdown(summary: ReplaySummary) -> List[Dict[str, object]]:
    counter: Counter = Counter()
    for result in summary.results:
        for failure in result.failures:
            counter[_failure_kind(failure)] += 1
    return [
        {"kind": kind, "count": count}
        for kind, count in sorted(counter.items(), key=lambda item: (-item[1], item[0]))
    ]


def render_markdown(summary: ReplaySummary, title: str = "Trace replay") -> str:
    lines: List[str] = []
    lines.append("# %s" % title)
    lines.append("")
    lines.append("| metric | value |")
    lines.append("| --- | --- |")
    lines.append("| cases | %d |" % summary.total)
    lines.append("| passed | %d |" % summary.passed)
    lines.append("| failed | %d |" % summary.failed)
    lines.append("| pass rate | %.1f%% |" % (100 * summary.pass_rate))
    lines.append("")

    if summary.total:
        lines.append("## Cases")
        lines.append("")
        lines.append("| case | result | steps | time |")
        lines.append("| --- | --- | --- | --- |")
        for result in summary.results:
            mark = "pass" if result.passed else "FAIL"
            lines.append(
                "| `%s` | %s | %d | %.0f ms |"
                % (result.case_id, mark, result.steps, result.duration_ms)
            )
        lines.append("")

    breakdown = failure_breakdown(summary)
    if breakdown:
        lines.append("## Failure breakdown")
        lines.append("")
        lines.append("| kind | count |")
        lines.append("| --- | --- |")
        for entry in breakdown:
            lines.append("| %s | %d |" % (entry["kind"], entry["count"]))
        lines.append("")

    failures = [result for result in summary.results if not result.passed]
    if failures:
        lines.append("## Failures")
        lines.append("")
        for result in failures:
            lines.append("### `%s`" % result.case_id)
            lines.append("")
            for failure in result.failures:
                lines.append("- %s" % failure)
            lines.append("")
            if result.tool_calls:
                lines.append("Tool calls made:")
                lines.append("")
                for call in result.tool_calls:
                    lines.append(
                        "- `%s(%s)`" % (call["name"], json.dumps(call["arguments"], sort_keys=True))
                    )
                lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by [tracegrade](https://github.com/Coisini-cyber/tracegrade). "
        "Tool calls were answered from recorded fixtures, not from live tools."
    )
    lines.append("")
    return "\n".join(lines)


def render_json(summary: ReplaySummary) -> str:
    data = summary.as_dict()
    data["failure_breakdown"] = failure_breakdown(summary)
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def render_console(summary: ReplaySummary) -> str:
    lines = []
    for result in summary.results:
        status = "PASS" if result.passed else "FAIL"
        lines.append("%s  %s  (%d steps)" % (status, result.case_id, result.steps))
        if not result.passed:
            for failure in result.failures:
                lines.append("      %s" % failure)
    lines.append("")
    lines.append(
        "%d/%d passed (%.1f%%)"
        % (summary.passed, summary.total, 100 * summary.pass_rate)
    )
    return "\n".join(lines)
